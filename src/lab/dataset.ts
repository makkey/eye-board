export interface Sentence {
  /** 文節ごとの表記 */
  surfaces: string[];
  /** 文節ごとの読み（ひらがな） */
  readings: string[];
}

/** 「表記 | 読み」の行を読み込む。読みだけの行（| なし）も受け付ける */
export function parseSentences(text: string): { sentences: Sentence[]; errors: string[] } {
  const sentences: Sentence[] = [];
  const errors: string[] = [];
  text.split('\n').forEach((line, i) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const [left, right] = trimmed.includes('|') ? trimmed.split('|') : [trimmed, trimmed];
    const surfaces = left.trim().split(/[\s　]+/);
    const readings = right.trim().split(/[\s　]+/);
    if (surfaces.length !== readings.length) {
      errors.push(`${i + 1}行目：表記と読みの文節の数が違います`);
      return;
    }
    sentences.push({ surfaces, readings });
  });
  return { sentences, errors };
}
