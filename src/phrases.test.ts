import { describe, expect, it } from 'vitest';
import { splitPhrase } from './phrases';

const split = (text: string, reading: string) => splitPhrase(text, reading).map((p) => `${p.text}(${p.reading})`).join('｜');

describe('splitPhrase', () => {
  it('名詞の後の助詞や、ひらがなの後の漢字で区切る', () => {
    expect(split('明後日はどう', 'あさってはどう')).toBe('明後日は(あさっては)｜どう(どう)');
    expect(split('明日は早いんだよね', 'あしたははやいんだよね')).toBe('明日は(あしたは)｜早いんだよね(はやいんだよね)');
    expect(split('ゲームがしたい', 'げーむがしたい')).toBe('ゲームが(げーむが)｜したい(したい)');
    expect(split('私の名前は悟です', 'わたしのなまえはさとるです')).toBe('私の(わたしの)｜名前は(なまえは)｜悟です(さとるです)');
    expect(split('ご飯を食べに行こう', 'ごはんをたべにいこう')).toBe('ご飯を(ごはんを)｜食べに(たべに)｜行こう(いこう)');
  });

  it('助詞が無くても、名詞の後の動詞や「て」の後の動詞で区切る', () => {
    expect(split('明後日やろう', 'あさってやろう')).toBe('明後日(あさって)｜やろう(やろう)');
    expect(split('電気つけて', 'でんきつけて')).toBe('電気(でんき)｜つけて(つけて)');
    expect(split('黙ってやろう', 'だまってやろう')).toBe('黙って(だまって)｜やろう(やろう)');
    expect(split('コーヒー飲む？', 'こーひーのむ')).toBe('コーヒー(こーひー)｜飲む？(のむ)');
    expect(split('大丈夫、ありがとう', 'だいじょうぶありがとう')).toBe('大丈夫、(だいじょうぶ)｜ありがとう(ありがとう)');
  });

  it('送りがなや する・です・ている では切らない', () => {
    for (const [t, r] of [
      ['上がってください', 'あがってください'],
      ['勉強している', 'べんきょうしている'],
      ['書かない', 'かかない'],
      ['ありがとうございます', 'ありがとうございます'],
      ['すごーい', 'すごおい'],
    ]) {
      expect(splitPhrase(t, r).length, t).toBeLessThanOrEqual(t === '上がってください' ? 2 : 1);
    }
    expect(split('上がってください', 'あがってください')).toBe('上がって(あがって)｜ください(ください)');
  });

  it('漢字が続く所や、読みが表記と合わない時は切らない', () => {
    expect(split('明後日買おう', 'あさってかおう')).toBe('明後日買おう(あさってかおう)');
    expect(split('ベッドで寝る', 'べっとでねる')).toBe('ベッドで寝る(べっとでねる)');
  });
});
